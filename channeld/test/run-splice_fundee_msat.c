/* Unit test for relative_splice_balance_fundee().
 *
 * hsmd_setup_channel's push_value is the fundee's balance at the start
 * of the new channel era: its pre-splice balance plus its funding
 * contribution.  The splicing opener_relative/accepter_relative fields
 * are satoshi amounts selected by SPLICE role, so the function must
 * (a) pick the contribution of the side that did not open the CHANNEL,
 * (b) convert sat -> msat, and (c) add the pre-splice balance.  This
 * pins that contract, byte-exact, through the real code in
 * channeld.c.
 *
 * Following hsmd/test/run-bad-request-close.c, we pull in channeld.c
 * itself (renaming its main) so the static function is testable.
 */
#include "config.h"
#include <sys/wait.h>
#include <unistd.h>
#include <ccan/array_size/array_size.h>
#include <ccan/err/err.h>
#include <common/setup.h>
#include <common/status.h>

int unused_main(int argc, char *argv[]);
#define main unused_main
#include "../channeld.c"
#undef main

