/* Unit test for relative_splice_balance_fundee().
 *
 * The opener_relative/accepter_relative splicing fields are satoshi
 * amounts, while the hsmd_setup_channel push_value field the function
 * feeds is amount_msat.  The function must convert (sat -> msat), not
 * reinterpret the raw integer: this pins that contract, byte-exact,
 * through the real code in channeld.c.
 *
 * Following hsmd/test/run-bad-request-close.c, we pull in channeld.c
 * itself (renaming its main) so the static function is testable.
 */
